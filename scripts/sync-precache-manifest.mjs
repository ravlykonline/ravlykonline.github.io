import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PAGES_PUBLICATION_MANIFEST } from './build-pages-artifact.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const defaultProjectRoot = path.resolve(__dirname, '..');
const START_MARKER = '// BEGIN GENERATED PRECACHE MANIFEST';
const END_MARKER = '// END GENERATED PRECACHE MANIFEST';

function toPosixPath(relativePath) {
    return relativePath.split(path.sep).join('/');
}

function listFilesRecursively(projectRoot, relativeDirectory) {
    const absoluteDirectory = path.join(projectRoot, relativeDirectory);
    if (!fs.existsSync(absoluteDirectory)) {
        throw new Error(`Missing published directory: ${relativeDirectory}`);
    }

    return fs.readdirSync(absoluteDirectory, { withFileTypes: true })
        .flatMap((entry) => {
            const relativePath = path.join(relativeDirectory, entry.name);
            return entry.isDirectory()
                ? listFilesRecursively(projectRoot, relativePath)
                : [toPosixPath(relativePath)];
        });
}

export function listRootPublicationFiles({ projectRoot = defaultProjectRoot } = {}) {
    const rootManifest = PAGES_PUBLICATION_MANIFEST.root;
    const publishedPaths = [
        ...rootManifest.files,
        ...rootManifest.directories.flatMap((directory) =>
            listFilesRecursively(projectRoot, directory)
        ),
    ].map(toPosixPath);

    const excludedPaths = new Set((rootManifest.excludes || []).map(toPosixPath));
    return [...new Set(publishedPaths)]
        .filter((relativePath) => !excludedPaths.has(relativePath))
        .sort();
}

function collectVersionedHtmlAssets(projectRoot, publicationFiles, precacheExtensions) {
    const publicationSet = new Set(publicationFiles);
    const versionedUrls = new Set();

    publicationFiles
        .filter((relativePath) => path.posix.extname(relativePath) === '.html')
        .forEach((relativePath) => {
            const html = fs.readFileSync(path.join(projectRoot, relativePath), 'utf8');
            for (const match of html.matchAll(/(?:href|src)="([^"#?]+\?[^"#]+)"/g)) {
                const reference = match[1];
                if (/^(?:[a-z]+:|\/\/)/i.test(reference)) continue;

                const [referencePath] = reference.split('?');
                const resolvedPath = toPosixPath(path.posix.normalize(
                    path.posix.join(path.posix.dirname(relativePath), referencePath)
                )).replace(/^\.\//, '').replace(/^\//, '');
                const extension = path.posix.extname(resolvedPath).toLowerCase();

                if (publicationSet.has(resolvedPath) && precacheExtensions.has(extension)) {
                    const query = reference.slice(referencePath.length);
                    versionedUrls.add(`/${resolvedPath}${query}`);
                }
            }
        });

    return [...versionedUrls].sort();
}

export function buildPrecacheManifest({ projectRoot = defaultProjectRoot } = {}) {
    const rootManifest = PAGES_PUBLICATION_MANIFEST.root;
    const config = rootManifest.precache;
    if (!config) {
        throw new Error('PAGES_PUBLICATION_MANIFEST.root.precache is required.');
    }

    const publicationFiles = listRootPublicationFiles({ projectRoot });
    const precacheExtensions = new Set(config.extensions);
    const excludedPaths = new Set(config.excludes || []);
    const staticUrls = publicationFiles
        .filter((relativePath) => !excludedPaths.has(relativePath))
        .filter((relativePath) => precacheExtensions.has(path.posix.extname(relativePath).toLowerCase()))
        .map((relativePath) => `/${relativePath}`);
    const versionedUrls = collectVersionedHtmlAssets(
        projectRoot,
        publicationFiles,
        precacheExtensions
    );

    return {
        extensions: [...precacheExtensions],
        urls: [...new Set([
            ...(config.routeAliases || []),
            ...staticUrls,
            ...versionedUrls,
        ])],
    };
}

function renderGeneratedBlock(manifest) {
    const extensions = manifest.extensions.map((extension) => `    '${extension}',`).join('\n');
    const urls = manifest.urls.map((url) => `    '${url}',`).join('\n');

    return [
        START_MARKER,
        '// Generated by scripts/sync-precache-manifest.mjs from',
        '// PAGES_PUBLICATION_MANIFEST.root. Do not edit this block manually.',
        'const CACHEABLE_EXTENSIONS = new Set([',
        extensions,
        ']);',
        '',
        'const PRECACHE_URLS = [',
        urls,
        '];',
        END_MARKER,
    ].join('\n');
}

export function syncPrecacheManifest({
    projectRoot = defaultProjectRoot,
    checkOnly = false,
} = {}) {
    const swPath = path.join(projectRoot, 'sw.js');
    const original = fs.readFileSync(swPath, 'utf8');
    const startIndex = original.indexOf(START_MARKER);
    const endIndex = original.indexOf(END_MARKER);

    if (startIndex === -1 || endIndex <= startIndex) {
        throw new Error('sw.js is missing generated precache manifest markers.');
    }

    const generatedBlock = renderGeneratedBlock(buildPrecacheManifest({ projectRoot }));
    const updated = original.slice(0, startIndex) + generatedBlock
        + original.slice(endIndex + END_MARKER.length);

    if (updated === original) {
        console.log('Precache manifest is synchronized.');
        return false;
    }

    if (checkOnly) {
        throw new Error('sw.js precache manifest is stale. Run npm run precache:sync.');
    }

    fs.writeFileSync(swPath, updated, 'utf8');
    console.log('Updated sw.js precache manifest.');
    return true;
}

const isCliRun = process.argv[1] && path.resolve(process.argv[1]) === __filename;
if (isCliRun) {
    syncPrecacheManifest({ checkOnly: process.argv.includes('--check') });
}
